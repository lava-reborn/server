"""Build data/questgen_setcraft.json: the clothing rework, the parts upgrade
and the clothing cheques of every town slice server/setcraft.py names.

The rows are setcraft.generate()'s -- one mechanism, a slice of data per
town (setcraft.SLICES), so a town that opens adds a slice and runs this
again. A slice whose "rows" are off (Вади-Хальфа's since 2026-10-09: the
owner took its clothing craftsmen away) still writes its rows, with give
and take [] and the why saying so. The server loads the file beside data/quests.json (server/quests.py
companion_paths), and data/build_orig_misc.py reads it for the string
table; its texts are DESIGNED templates on the original's lines, not the
original's rows (those name the original's families, which the owner's
ladder has moved), so none of it is pinned in VERIFIED.

What the rows and the module quote of the original is checked here against
texts.xml before anything is written: setcraft.ORIGINAL line by line, and
the cheques' name and description rows (setcraft.CHEQUE_ROWS), whose words
the cheques are named by. A mismatch stops the build.

Run from WSL (LAVA_RES is required: the reworked pieces and the cheques are
found in objects.xml; LAVA_ORIG_TEXTS moves the source):
    LAVA_RES=/mnt/c/Users/gmkrt/OneDrive/Desktop/lava/res python3 data/build_setcraft.py
"""
import html
import io
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "server"))

import setcraft  # noqa: E402

DEFAULT_TEXTS = "/mnt/c/Users/gmkrt/Downloads/texts.xml"
OUT = os.path.join(HERE, setcraft.OUT_NAME)
ITEM_ROW = re.compile(r'<item id="(\d+)">(.*?)</item>', re.S)


def load_texts(path):
    with io.open(path, encoding="utf-8") as fh:
        return {int(i): html.unescape(t) for i, t in ITEM_ROW.findall(fh.read())}


def check_original(texts):
    """setcraft's quotes and cheque rows are the original's, or SystemExit."""
    for sid, text in setcraft.ORIGINAL.items():
        if texts.get(sid) != text:
            raise SystemExit("texts.xml %d is %r, setcraft quotes %r" % (sid, texts.get(sid), text))
    for variant, first in setcraft.CHEQUE_ROWS.items():
        for k, level in enumerate(setcraft.CHEQUE_LEVELS):
            name, desc = texts.get(first + 2 * k), texts.get(first + 2 * k + 1)
            if name != "Чек на одежду [%d][%s]" % (level, variant) \
                    or desc != "Используется для улучшения одежды [%d][%s]." % (level, variant):
                raise SystemExit("texts.xml %d/%d are not the cheque [%d][%s]: %r / %r"
                                 % (first + 2 * k, first + 2 * k + 1, level, variant, name, desc))


def build(texts_path=None):
    texts_path = texts_path or os.environ.get("LAVA_ORIG_TEXTS") or DEFAULT_TEXTS
    check_original(load_texts(texts_path))
    rows = setcraft.generate_all()
    counts = {}
    for q in rows:
        counts[q["craft"]] = counts.get(q["craft"], 0) + 1
    meta = {
        "about": "GENERATED by data/build_setcraft.py from server/setcraft.py -- do not edit: "
                 "change the module (its SLICES, its numbers) and run the builder.",
        "slices": {name: dict({"band": list(s["band"]), "parts_band": list(s["parts_band"]),
                               "craftsmen": {str(k): v for k, v in sorted(s["craftsmen"].items())}},
                              **({"off": dict(s["off"])} if s.get("off") else {}))
                   for name, s in setcraft.SLICES.items()},
        "counts": counts,
        "types": [rows[0]["type"], rows[-1]["type"]] if rows else [],
    }
    return {"_meta": meta, "quests": rows}


def dumps(doc):
    return json.dumps(doc, ensure_ascii=False, indent=1) + "\n"


def main():
    doc = build()
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(dumps(doc))
    print("wrote %s: %d rows %s" % (OUT, len(doc["quests"]), doc["_meta"]["counts"]))


if __name__ == "__main__":
    main()
